import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import type { IncomingMessage, ServerResponse } from "node:http";
import { resolve } from "node:path";
import type { Plugin } from "vite";

/**
 * Dev-server endpoints for Deck Builder (prototypes/deck-builder).
 *
 * POST /__deck-builder/publish writes a deck into prototypes/<slug>/ (deck.json, slide
 * images, an index.html and a tiny main.tsx that mounts src/deck) and adds or updates
 * its projects.json entry. Nothing is committed or pushed.
 *
 * GET /__deck-builder/figma?path=/v1/... proxies the Figma REST API, for browsers
 * where a direct request is blocked.
 *
 * Both exist only on the local dev server; the deployed site is static.
 */

const SLUG_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const RESERVED = new Set(["assets", "src", "public", "prototypes", "deck-builder", "templates"]);

interface PublishSlideFigma {
  id: string;
  kind: "figma";
  nodeId: string;
  name: string;
  image: string;
  hidden?: boolean;
}
interface PublishSlideWeb {
  id: string;
  kind: "web";
  url: string;
  title: string;
}
interface PublishBody {
  deck: {
    name: string;
    slug: string;
    source: { figmaUrl: string; fileKey: string } | null;
    figmaLive?: boolean;
    slides: Array<PublishSlideFigma | PublishSlideWeb>;
  };
  /** Slide id → data URL, for images the browser could download itself. */
  images?: Record<string, string>;
}

function readBody(req: IncomingMessage) {
  return new Promise<string>((done, fail) => {
    const chunks: Buffer[] = [];
    req.on("data", (chunk: Buffer) => chunks.push(chunk));
    req.on("end", () => done(Buffer.concat(chunks).toString("utf8")));
    req.on("error", fail);
  });
}

function send(res: ServerResponse, status: number, body: unknown) {
  res.statusCode = status;
  res.setHeader("Content-Type", "application/json");
  res.end(JSON.stringify(body));
}

function escapeHtml(value: string) {
  return value.replace(/[&<>"]/g, (char) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[char]!);
}

function extensionFor(contentType: string | null) {
  if (contentType?.includes("webp")) return "webp";
  if (contentType?.includes("jpeg")) return "jpg";
  if (contentType?.includes("svg")) return "svg";
  return "png";
}

async function imageBytes(slide: PublishSlideFigma, dataUrl: string | undefined) {
  if (dataUrl) {
    const match = /^data:([^;,]+)?(;base64)?,(.*)$/s.exec(dataUrl);
    if (match) {
      const bytes = match[2] ? Buffer.from(match[3], "base64") : Buffer.from(decodeURIComponent(match[3]));
      return { bytes, ext: extensionFor(match[1] ?? null) };
    }
  }
  const response = await fetch(slide.image);
  if (!response.ok) throw new Error(`Couldn't download the image for "${slide.name}" (${response.status}). Reload slides from Figma and try again.`);
  return { bytes: Buffer.from(await response.arrayBuffer()), ext: extensionFor(response.headers.get("content-type")) };
}

const indexHtml = (name: string) => `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="robots" content="noindex" />
    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link href="https://fonts.googleapis.com/css2?family=Geist:wght@400;500;600&family=Geist+Mono:wght@400;500&display=swap" rel="stylesheet" />
    <title>${escapeHtml(name)}</title>
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="./src/main.tsx"></script>
  </body>
</html>
`;

const mainTsx = `// Generated by Deck Builder. Edit the deck in /deck-builder/ and publish again rather than editing here.
import { mountDeck } from "../../../src/deck/mount";
import type { Deck } from "../../../src/deck/types";
import deck from "../deck.json";

const images = import.meta.glob("../slides/*", { eager: true, query: "?url", import: "default" }) as Record<string, string>;

mountDeck(deck as unknown as Deck, images);
`;

async function publish(root: string, body: PublishBody) {
  const { deck } = body;
  const name = deck?.name?.trim();
  const slug = deck?.slug?.trim();
  if (!name) return { status: 400, body: { error: "Give the deck a name." } };
  if (!slug || !SLUG_PATTERN.test(slug)) {
    return { status: 400, body: { error: "Use lowercase letters, numbers and single hyphens in the URL name." } };
  }
  if (RESERVED.has(slug)) return { status: 400, body: { error: `"${slug}" is reserved. Choose another URL name.` } };

  const dir = resolve(root, "prototypes", slug);
  const deckFile = resolve(dir, "deck.json");
  if (existsSync(dir)) {
    const isDeck = existsSync(deckFile);
    // Publishing to a deck's URL again updates that deck; other prototypes are never overwritten.
    if (!isDeck) return { status: 409, body: { error: `"${slug}" is already used by another Sandbox project. Choose another URL name.` } };
  }

  const slides = deck.slides.filter((slide) => !(slide.kind === "figma" && slide.hidden));
  if (slides.length === 0) return { status: 400, body: { error: "The deck has no slides to publish." } };
  for (const slide of slides) {
    if (slide.kind === "web" && !slide.url) return { status: 400, body: { error: "Every web slide needs a URL." } };
  }

  // Download everything before touching the folder, so a failure leaves an existing deck intact.
  const files = new Map<string, Buffer>();
  const output: Array<PublishSlideFigma | PublishSlideWeb> = [];
  let figmaCount = 0;
  for (const slide of slides) {
    if (slide.kind === "web") {
      output.push({ id: slide.id, kind: "web", url: slide.url, title: slide.title });
      continue;
    }
    figmaCount += 1;
    const { bytes, ext } = await imageBytes(slide, body.images?.[slide.id]);
    const file = `${String(figmaCount).padStart(2, "0")}.${ext}`;
    files.set(file, bytes);
    output.push({ id: slide.id, kind: "figma", nodeId: slide.nodeId, name: slide.name, image: file });
  }

  const createdAt = existsSync(deckFile)
    ? (JSON.parse(readFileSync(deckFile, "utf8")) as { createdAt?: string }).createdAt
    : undefined;
  const today = new Date().toISOString().slice(0, 10);

  rmSync(resolve(dir, "slides"), { recursive: true, force: true });
  mkdirSync(resolve(dir, "slides"), { recursive: true });
  mkdirSync(resolve(dir, "src"), { recursive: true });
  for (const [file, bytes] of files) writeFileSync(resolve(dir, "slides", file), bytes);
  writeFileSync(
    deckFile,
    `${JSON.stringify({ version: 1, name, slug, createdAt: createdAt ?? today, source: deck.source, figmaLive: Boolean(deck.figmaLive), slides: output }, null, 2)}\n`,
  );
  writeFileSync(resolve(dir, "index.html"), indexHtml(name));
  writeFileSync(resolve(dir, "src", "main.tsx"), mainTsx);

  // Registry: update this deck's entry in place, or append one. Other entries are left as they are.
  const registryFile = resolve(root, "projects.json");
  const registry = JSON.parse(readFileSync(registryFile, "utf8")) as { projects: Array<Record<string, unknown>> };
  const designSource = deck.source ? { type: "figma", reference: deck.source.figmaUrl } : null;
  const existing = registry.projects.find((project) => project.slug === slug);
  if (existing) {
    existing.name = name;
    existing.designSource = designSource;
  } else {
    registry.projects.push({
      name,
      slug,
      path: `prototypes/${slug}/`,
      purpose: "client-demo",
      status: "active",
      createdAt: createdAt ?? today,
      designSource,
      publishedUrl: null,
      notes: "Presentation published from Deck Builder: Figma slides with live web pages in between.",
    });
  }
  writeFileSync(registryFile, `${JSON.stringify(registry, null, 2)}\n`);

  return {
    status: 200,
    body: {
      slug,
      path: `/${slug}/`,
      folder: `prototypes/${slug}/`,
      figmaSlides: figmaCount,
      webSlides: output.length - figmaCount,
      replaced: Boolean(existing),
    },
  };
}

export function deckPublish(): Plugin {
  let root = process.cwd();
  return {
    name: "deck-builder-publish",
    apply: "serve",
    configResolved(config) {
      root = config.root;
    },
    configureServer(server) {
      server.middlewares.use("/__deck-builder/publish", (req, res) => {
        if (req.method !== "POST") return send(res, 405, { error: "Use POST." });
        readBody(req)
          .then((raw) => publish(root, JSON.parse(raw) as PublishBody))
          .then((result) => send(res, result.status, result.body))
          .catch((error: unknown) => send(res, 500, { error: error instanceof Error ? error.message : "Publishing failed." }));
      });

      // GET /__deck-builder/slug?slug=… says what a URL name is used by: nothing, a deck (which
      // publishing replaces) or another project (which it never touches), so the form can warn first.
      server.middlewares.use("/__deck-builder/slug", (req, res) => {
        const slug = new URL(req.url ?? "", "http://localhost").searchParams.get("slug") ?? "";
        if (!SLUG_PATTERN.test(slug)) return send(res, 200, { usedBy: null });
        if (RESERVED.has(slug)) return send(res, 200, { usedBy: "reserved" });
        const dir = resolve(root, "prototypes", slug);
        if (!existsSync(dir)) return send(res, 200, { usedBy: null });
        send(res, 200, { usedBy: existsSync(resolve(dir, "deck.json")) ? "deck" : "project" });
      });

      server.middlewares.use("/__deck-builder/figma", (req, res) => {
        const path = new URL(req.url ?? "", "http://localhost").searchParams.get("path") ?? "";
        const token = req.headers["x-figma-token"];
        if (!path.startsWith("/v1/") || typeof token !== "string") return send(res, 400, { error: "Bad request." });
        fetch(`https://api.figma.com${path}`, { headers: { "X-Figma-Token": token } })
          .then(async (response) => {
            res.statusCode = response.status;
            res.setHeader("Content-Type", "application/json");
            res.end(await response.text());
          })
          .catch(() => send(res, 502, { err: "Couldn't reach Figma." }));
      });
    },
  };
}
